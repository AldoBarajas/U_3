BEGIN;
CREATE SCHEMA IF NOT EXISTS biblioteca;
SET search_path TO biblioteca, public;

-- Supertipo: especializacion total y disjunta (reforzada por triggers diferibles).
CREATE TABLE persona (
    id_persona BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombres VARCHAR(80) NOT NULL,
    apellido_paterno VARCHAR(80) NOT NULL,
    apellido_materno VARCHAR(80),
    correo VARCHAR(254) NOT NULL,
    tipo_persona VARCHAR(12) NOT NULL,
    CONSTRAINT pk_persona PRIMARY KEY (id_persona),
    CONSTRAINT uq_persona_correo UNIQUE (correo),
    CONSTRAINT uq_persona_id_tipo UNIQUE (id_persona, tipo_persona),
    CONSTRAINT ck_persona_nombres CHECK (length(trim(nombres)) > 0 AND length(trim(apellido_paterno)) > 0),
    CONSTRAINT ck_persona_tipo CHECK (tipo_persona IN ('ESTUDIANTE', 'DOCENTE'))
);

CREATE TABLE estudiante (
    id_persona BIGINT NOT NULL,
    tipo_persona VARCHAR(12) NOT NULL DEFAULT 'ESTUDIANTE',
    matricula VARCHAR(20) NOT NULL,
    semestre SMALLINT NOT NULL,
    CONSTRAINT pk_estudiante PRIMARY KEY (id_persona),
    CONSTRAINT uq_estudiante_matricula UNIQUE (matricula),
    CONSTRAINT ck_estudiante_tipo CHECK (tipo_persona = 'ESTUDIANTE'),
    CONSTRAINT ck_estudiante_semestre CHECK (semestre BETWEEN 1 AND 16),
    CONSTRAINT fk_estudiante_persona FOREIGN KEY (id_persona, tipo_persona)
        REFERENCES persona (id_persona, tipo_persona)
        ON UPDATE RESTRICT ON DELETE CASCADE
);

CREATE TABLE docente (
    id_persona BIGINT NOT NULL,
    tipo_persona VARCHAR(12) NOT NULL DEFAULT 'DOCENTE',
    numero_empleado VARCHAR(20) NOT NULL,
    departamento VARCHAR(100) NOT NULL,
    CONSTRAINT pk_docente PRIMARY KEY (id_persona),
    CONSTRAINT uq_docente_numero UNIQUE (numero_empleado),
    CONSTRAINT ck_docente_tipo CHECK (tipo_persona = 'DOCENTE'),
    CONSTRAINT ck_docente_departamento CHECK (length(trim(departamento)) > 0),
    CONSTRAINT fk_docente_persona FOREIGN KEY (id_persona, tipo_persona)
        REFERENCES persona (id_persona, tipo_persona)
        ON UPDATE RESTRICT ON DELETE CASCADE
);

-- Atributo multivalorado de Persona (0..* telefonos).
CREATE TABLE persona_telefono (
    id_persona BIGINT NOT NULL,
    telefono VARCHAR(20) NOT NULL,
    CONSTRAINT pk_persona_telefono PRIMARY KEY (id_persona, telefono),
    CONSTRAINT ck_telefono_no_vacio CHECK (length(trim(telefono)) BETWEEN 7 AND 20),
    CONSTRAINT fk_telefono_persona FOREIGN KEY (id_persona)
        REFERENCES persona (id_persona) ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE TABLE libro (
    isbn VARCHAR(17) NOT NULL,
    titulo VARCHAR(200) NOT NULL,
    anio_publicacion SMALLINT NOT NULL,
    CONSTRAINT pk_libro PRIMARY KEY (isbn),
    CONSTRAINT ck_libro_isbn CHECK (isbn ~ '^([0-9]{13}|[0-9]{9}[0-9X])$'),
    CONSTRAINT ck_libro_titulo CHECK (length(trim(titulo)) > 0),
    CONSTRAINT ck_libro_anio CHECK (anio_publicacion BETWEEN 1450 AND 2100)
);

CREATE TABLE autor (
    id_autor BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(160) NOT NULL,
    CONSTRAINT pk_autor PRIMARY KEY (id_autor),
    CONSTRAINT ck_autor_nombre CHECK (length(trim(nombre)) > 0)
);

-- Relacion N:M ESCRIBE. Libro exige al menos un autor (trigger diferible mas abajo).
CREATE TABLE libro_autor (
    isbn VARCHAR(17) NOT NULL,
    id_autor BIGINT NOT NULL,
    CONSTRAINT pk_libro_autor PRIMARY KEY (isbn, id_autor),
    CONSTRAINT fk_la_libro FOREIGN KEY (isbn) REFERENCES libro (isbn)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_la_autor FOREIGN KEY (id_autor) REFERENCES autor (id_autor)
        ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE TABLE coleccion (
    id_coleccion BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(100) NOT NULL,
    CONSTRAINT pk_coleccion PRIMARY KEY (id_coleccion),
    CONSTRAINT uq_coleccion_nombre UNIQUE (nombre),
    CONSTRAINT ck_coleccion_nombre CHECK (length(trim(nombre)) > 0)
);

-- Relacion N:M AGRUPA.
CREATE TABLE libro_coleccion (
    isbn VARCHAR(17) NOT NULL,
    id_coleccion BIGINT NOT NULL,
    CONSTRAINT pk_libro_coleccion PRIMARY KEY (isbn, id_coleccion),
    CONSTRAINT fk_lc_libro FOREIGN KEY (isbn) REFERENCES libro (isbn)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_lc_coleccion FOREIGN KEY (id_coleccion) REFERENCES coleccion (id_coleccion)
        ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE TABLE ejemplar (
    id_ejemplar BIGINT GENERATED BY DEFAULT AS IDENTITY,
    isbn VARCHAR(17) NOT NULL,
    codigo_inventario VARCHAR(30) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'DISPONIBLE',
    CONSTRAINT pk_ejemplar PRIMARY KEY (id_ejemplar),
    CONSTRAINT uq_ejemplar_codigo UNIQUE (codigo_inventario),
    CONSTRAINT ck_ejemplar_estado CHECK (estado IN ('DISPONIBLE', 'EN_REPARACION', 'BAJA')),
    CONSTRAINT fk_ejemplar_libro FOREIGN KEY (isbn) REFERENCES libro (isbn)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

-- Entidad de evento. Los FKs historicos no permiten eliminacion en cascada.
CREATE TABLE prestamo (
    id_prestamo BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_persona BIGINT NOT NULL,
    id_ejemplar BIGINT NOT NULL,
    fecha_salida DATE NOT NULL,
    fecha_limite DATE NOT NULL,
    fecha_devolucion DATE,
    CONSTRAINT pk_prestamo PRIMARY KEY (id_prestamo),
    CONSTRAINT ck_prestamo_fechas CHECK (
        fecha_limite >= fecha_salida AND
        (fecha_devolucion IS NULL OR fecha_devolucion >= fecha_salida)
    ),
    CONSTRAINT fk_prestamo_persona FOREIGN KEY (id_persona) REFERENCES persona (id_persona)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_prestamo_ejemplar FOREIGN KEY (id_ejemplar) REFERENCES ejemplar (id_ejemplar)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

-- Restriccion RN07: un ejemplar solo puede tener 1 prestamo activo (devolucion IS NULL).
CREATE UNIQUE INDEX ux_prestamo_ejemplar_activo
    ON prestamo (id_ejemplar) WHERE fecha_devolucion IS NULL;

CREATE TABLE incidencia (
    id_incidencia BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_prestamo BIGINT NOT NULL,
    tipo VARCHAR(12) NOT NULL,
    fecha DATE NOT NULL,
    observacion TEXT NOT NULL,
    CONSTRAINT pk_incidencia PRIMARY KEY (id_incidencia),
    CONSTRAINT ck_incidencia_tipo CHECK (tipo IN ('DANO', 'PERDIDA', 'RETRASO', 'OTRA')),
    CONSTRAINT ck_incidencia_observacion CHECK (length(trim(observacion)) > 0),
    CONSTRAINT fk_incidencia_prestamo FOREIGN KEY (id_prestamo) REFERENCES prestamo (id_prestamo)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

-- Indices para joins y verificaciones de integridad referencial.
CREATE INDEX ix_prestamo_persona ON prestamo (id_persona);
CREATE INDEX ix_incidencia_prestamo ON incidencia (id_prestamo);
CREATE INDEX ix_ejemplar_isbn ON ejemplar (isbn);
CREATE INDEX ix_la_autor ON libro_autor (id_autor);
CREATE INDEX ix_lc_coleccion ON libro_coleccion (id_coleccion);

-- RN04: especializacion TOTAL y DISJUNTA verificada al finalizar la transaccion.
-- Las FK compuestas + CHECK impiden subtipos incompatibles; el trigger exige que exista el correcto.
CREATE FUNCTION fn_comprobar_subtipo() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    v_id BIGINT;
    v_tipo VARCHAR(12);
BEGIN
    IF TG_TABLE_NAME = 'persona' THEN
        v_id := NEW.id_persona;
    ELSIF TG_OP = 'INSERT' THEN
        v_id := NEW.id_persona;
    ELSE
        v_id := OLD.id_persona;
    END IF;

    SELECT p.tipo_persona INTO v_tipo FROM persona p WHERE p.id_persona = v_id;
    IF NOT FOUND THEN RETURN NULL; END IF; -- Persona eliminada en la misma transaccion.

    IF v_tipo = 'ESTUDIANTE' AND NOT EXISTS (
        SELECT 1 FROM estudiante e WHERE e.id_persona = v_id
    ) THEN
        RAISE EXCEPTION 'La persona % requiere fila ESTUDIANTE', v_id
            USING ERRCODE = '23514';
    ELSIF v_tipo = 'DOCENTE' AND NOT EXISTS (
        SELECT 1 FROM docente d WHERE d.id_persona = v_id
    ) THEN
        RAISE EXCEPTION 'La persona % requiere fila DOCENTE', v_id
            USING ERRCODE = '23514';
    END IF;
    RETURN NULL;
END;
$$;
CREATE CONSTRAINT TRIGGER ct_persona_subtipo
    AFTER INSERT OR UPDATE ON persona DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION fn_comprobar_subtipo();
CREATE CONSTRAINT TRIGGER ct_estudiante_subtipo
    AFTER UPDATE OR DELETE ON estudiante DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION fn_comprobar_subtipo();
CREATE CONSTRAINT TRIGGER ct_docente_subtipo
    AFTER UPDATE OR DELETE ON docente DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION fn_comprobar_subtipo();

-- RN02: cada Libro debe tener al menos 1 Autor al confirmar la transaccion.
CREATE FUNCTION fn_comprobar_autores() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    v_isbn VARCHAR(17);
BEGIN
    IF TG_TABLE_NAME = 'libro' THEN
        v_isbn := NEW.isbn;
    ELSE
        v_isbn := OLD.isbn;
    END IF;
    IF EXISTS (SELECT 1 FROM libro l WHERE l.isbn = v_isbn)
       AND NOT EXISTS (SELECT 1 FROM libro_autor la WHERE la.isbn = v_isbn) THEN
        RAISE EXCEPTION 'El libro % debe tener al menos un autor', v_isbn
            USING ERRCODE = '23514';
    END IF;
    RETURN NULL;
END;
$$;
CREATE CONSTRAINT TRIGGER ct_libro_autoria
    AFTER INSERT OR UPDATE ON libro DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION fn_comprobar_autores();
CREATE CONSTRAINT TRIGGER ct_libro_autor_retirado
    AFTER DELETE OR UPDATE ON libro_autor DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION fn_comprobar_autores();

-- Atributos derivados: vistas; no persisten datos redundantes.
CREATE VIEW vw_libro_antiguedad AS
SELECT isbn, titulo, anio_publicacion,
       EXTRACT(YEAR FROM CURRENT_DATE)::INTEGER - anio_publicacion AS edad_obra
FROM libro;

CREATE VIEW vw_prestamo_atraso AS
SELECT id_prestamo, id_persona, id_ejemplar, fecha_salida, fecha_limite, fecha_devolucion,
       GREATEST(0, COALESCE(fecha_devolucion, CURRENT_DATE) - fecha_limite) AS dias_atraso
FROM prestamo;

CREATE VIEW vw_disponibilidad AS
SELECT e.id_ejemplar, e.codigo_inventario, e.isbn, e.estado,
       (e.estado = 'DISPONIBLE' AND NOT EXISTS (
           SELECT 1 FROM prestamo p
           WHERE p.id_ejemplar = e.id_ejemplar AND p.fecha_devolucion IS NULL
       )) AS disponible
FROM ejemplar e;
COMMIT;
